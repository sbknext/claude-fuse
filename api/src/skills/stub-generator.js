/**
 * Skill stub generator (Story 1.5.6)
 *
 * Takes a skill_candidates row, fills the CANDIDATE template,
 * writes to data/skill-stubs/<sha256-prefix>-<YYYYMMDD>.md,
 * and returns { path, markdown }.
 *
 * Honesty rules:
 *   - CANDIDATE banner is always the first non-empty line.
 *   - AI-generated fields are labelled "AI:" inline.
 *   - Stub never claims the pattern is a mistake — it is a candidate.
 */
import { createHash } from 'crypto';
import { mkdirSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

/**
 * Resolve the stubs output directory.
 * Respects CLAUDE_FUSE_DATA_DIR env var; defaults to repo-root/data/skill-stubs.
 */
function stubsDir() {
  const dataDir = process.env.CLAUDE_FUSE_DATA_DIR
    ? resolve(process.env.CLAUDE_FUSE_DATA_DIR)
    : resolve(__dirname, '../../../data');
  return join(dataDir, 'skill-stubs');
}

/**
 * Generate the stub filename: <sha256-prefix>-<YYYYMMDD>.md
 * sha256-prefix = first 12 chars of the candidate's signature.
 */
function stubFilename(signature) {
  const prefix = signature.slice(0, 12);
  const now = new Date();
  const date =
    String(now.getFullYear()) +
    String(now.getMonth() + 1).padStart(2, '0') +
    String(now.getDate()).padStart(2, '0');
  return `${prefix}-${date}.md`;
}

/**
 * Build the Markdown stub from a skill_candidates row.
 *
 * @param {Object} candidate  - skill_candidates row
 * @param {Object} [aiResult] - optional { trigger: string, notes: string }
 * @returns {string}          - Markdown string
 */
export function buildStubMarkdown(candidate, aiResult = null) {
  const tools = JSON.parse(candidate.tool_sequence_json);
  const { frequency, example_session_ids_json, signature } = candidate;

  // Count distinct sessions from the stored JSON
  let distinctSessions = 0;
  try {
    const ids = JSON.parse(example_session_ids_json || '[]');
    if (Array.isArray(ids)) {
      distinctSessions = new Set(ids.flatMap((s) => String(s).split(','))).size;
    }
  } catch {
    distinctSessions = 0;
  }

  const toolsLabel = tools.join(' → ');
  const isoDate = new Date().toISOString();

  const aiTrigger = aiResult?.trigger
    ? `${aiResult.trigger} **[AI — candidate suggestion]**`
    : 'not generated';

  const aiNotes = aiResult?.notes
    ? `${aiResult.notes} **[AI — candidate suggestion]**`
    : '';

  // Steps: one bullet per tool
  const steps = tools
    .map((t, i) => `${i + 1}. ${t}: <!-- describe what this tool does in this context -->`)
    .join('\n');

  const notesAiLine = aiNotes
    ? `<!-- AI notes: ${aiNotes} -->\n`
    : '';

  return `<!-- CANDIDATE — generated by claude-fuse, not a validated skill -->
<!-- n-gram: ${toolsLabel} (×${frequency} across ${distinctSessions} sessions) -->
<!-- generated: ${isoDate} -->
<!-- sig: ${signature.slice(0, 16)} -->

# Skill: ${toolsLabel}

## Trigger
<!-- When should this skill run? Fill in the trigger condition. -->
<!-- AI: ${aiTrigger} -->

## Steps
<!-- One step per tool in the n-gram: -->
${steps}

## Notes
<!-- Frequency: ${frequency} · Sessions: ${distinctSessions} -->
<!-- Candidate — verify this pattern is intentional before promoting to a skill. -->
${notesAiLine}<!-- Promote this skill to Brain — \`brain memory_save skill:${tools[0].toLowerCase()}-${tools[tools.length - 1].toLowerCase()}\` -->
`;
}

/**
 * Generate a stub for a skill candidate, write it to disk, and return the path + markdown.
 *
 * @param {Object} candidate  - skill_candidates row (id, signature, tool_sequence_json, …)
 * @param {Object} [aiResult] - optional AI-suggested { trigger, notes }
 * @returns {{ path: string, markdown: string }}
 */
export function generateStub(candidate, aiResult = null) {
  const markdown = buildStubMarkdown(candidate, aiResult);

  const dir = stubsDir();
  mkdirSync(dir, { recursive: true });

  const filename = stubFilename(candidate.signature);
  const filePath = join(dir, filename);

  writeFileSync(filePath, markdown, 'utf8');

  return { path: filePath, filename, markdown };
}
